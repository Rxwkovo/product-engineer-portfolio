const $ = id => document.getElementById(id);
const fields = ['title', 'goal', 'audience', 'date', 'location', 'format', 'deliverables', 'tone'];
let draft = null;
let mode = 'demo';
const publicDemo = document.documentElement.dataset.mode === 'public-demo';

(publicDemo ? Promise.resolve({ modelConfigured: false }) : fetch('/api/status').then(r => r.json())).then(status => {
  $('mode-label').textContent = status.modelConfigured ? 'AI model connected' : (publicDemo ? 'Public demo parser · no AI model call' : 'Local demo parser · no model key');
}).catch(() => { $('mode-label').textContent = 'Mode unavailable'; });

function stage(value) {
  $('empty').classList.toggle('hidden', value !== 1);
  $('form-wrap').classList.toggle('hidden', value !== 2);
  $('confirmed').classList.toggle('hidden', value !== 3);
  for (let i = 1; i <= 3; i++) {
    const step = $('step-' + i);
    step.classList.toggle('active', i === value);
    if (i === value) step.setAttribute('aria-current', 'step');
    else step.removeAttribute('aria-current');
  }
  $('state-pill').textContent = value === 1 ? 'Awaiting input' : value === 2 ? 'Ready to review' : 'Confirmed';
  $('state-pill').classList.toggle('ready', value > 1);
}

function collect() {
  const data = {};
  for (const field of fields) data[field] = field === 'deliverables' ? $(field).value.split(',').map(s => s.trim()).filter(Boolean) : $(field).value.trim();
  data.open_questions = draft.open_questions;
  if (draft.resolved_questions && Object.keys(draft.resolved_questions).length) data.resolved_questions = draft.resolved_questions;
  return data;
}

function render(data) {
  draft = data;
  draft.open_questions = Array.isArray(data.open_questions) ? data.open_questions : [];
  draft.resolved_questions = {};
  $('review-notes').replaceChildren();
  $('review-notes').classList.add('hidden');
  for (const field of fields) $(field).value = Array.isArray(data[field]) ? data[field].join(', ') : data[field] || '';
  $('questions').replaceChildren(...data.open_questions.map(question => {
    const li = document.createElement('li');
    const text = document.createElement('span'); text.textContent = question;
    const resolve = document.createElement('button'); resolve.type = 'button'; resolve.textContent = 'Answer';
    resolve.addEventListener('click', () => {
      if (li.querySelector('input')) return;
      const answer = document.createElement('input');
      answer.type = 'text'; answer.setAttribute('aria-label', `Answer: ${question}`);
      answer.placeholder = 'Type your decision';
      const save = document.createElement('button'); save.type = 'button'; save.textContent = 'Save';
      save.addEventListener('click', () => {
        const value = answer.value.trim();
        if (!value) { answer.focus(); return; }
        draft.resolved_questions[question] = value;
        draft.open_questions = draft.open_questions.filter(item => item !== question);
        const note = document.createElement('p');
        const label = document.createElement('strong'); label.textContent = question;
        const answerText = document.createElement('span'); answerText.textContent = value;
        note.append(label, answerText);
        $('review-notes').append(note);
        $('review-notes').classList.remove('hidden');
        li.remove();
      });
      li.append(answer, save); answer.focus();
    });
    li.append(text, resolve); return li;
  }));
  $('mode-note').textContent = mode === 'ai' ? 'AI structured output · check every field before confirmation.' : 'Local demo parser · this result was not generated by an AI model.';
  stage(2);
}

$('generate').addEventListener('click', async () => {
  const button = $('generate'); button.disabled = true; button.textContent = 'Building draft…';
  $('error').classList.add('hidden'); $('error').textContent = '';
  document.querySelector('.draft-pane').classList.add('is-building');
  try {
    let result;
    if (publicDemo) {
      const input = FormaDemoParser.clean($('request').value);
      if (input.length < 15) throw new Error('Describe the request in at least 15 characters');
      result = { mode: 'demo', data: FormaDemoParser.demoExtract(input) };
    } else {
      const response = await fetch('/api/extract', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ input: $('request').value }) });
      result = await response.json();
      if (!response.ok) throw new Error(result.error || 'Could not generate a draft');
    }
    mode = result.mode; render(result.data);
    document.querySelectorAll('.field').forEach((el,i)=>el.style.setProperty('--field-i',i));
  } catch (error) { $('error').textContent = error.message; $('error').classList.remove('hidden'); }
  finally { document.querySelector('.draft-pane').classList.remove('is-building'); button.disabled = false; button.innerHTML = 'Build editable draft <span aria-hidden="true">↗</span>'; }
});
$('reset').addEventListener('click', () => stage(1));
$('confirm').addEventListener('click', () => { draft = collect(); $('json-preview').textContent = JSON.stringify(draft, null, 2); stage(3); });
$('edit').addEventListener('click', () => stage(2));
$('download').addEventListener('click', () => {
  const blob = new Blob([JSON.stringify(draft, null, 2)], { type: 'application/json' });
  const link = document.createElement('a'); link.href = URL.createObjectURL(blob); link.download = 'confirmed-intake.json'; link.click(); setTimeout(() => URL.revokeObjectURL(link.href), 1000);
});
